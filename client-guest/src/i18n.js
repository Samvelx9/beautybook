// The languages this master's page is in, from GET /api/site. Set once, before
// the first render that shows the site, like the currency and timezone.
let siteLanguages = null;
export function setSiteLanguages(languages) {
  siteLanguages = Array.isArray(languages) ? languages : null;
}
export function getSiteLanguages() {
  return siteLanguages;
}

// The master's minimum booking notice in minutes (GET /api/site), for the
// sentences that tell guests about it.
let minNoticeMinutes = 90;
export function setMinNotice(minutes) {
  if (Number.isInteger(minutes)) minNoticeMinutes = minutes;
}
export function getMinNotice() {
  return minNoticeMinutes;
}

